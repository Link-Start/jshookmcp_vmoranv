function show(name, bytes, arch, mode) {
  const d = new cs.Capstone(arch, mode);
  const insns = d.disasm(new Uint8Array(bytes), 0n);
  console.log(`=== ${name} (${bytes.length} bytes) ===`);
  for (const insn of insns) {
    console.log(`  ${String(insn.address)}: ${insn.mnemonic} ${insn.op_str}`);
  }
  d.close();
}

